// Claude Code on this machine authenticates through the gateway; URL, credentials and model aliases are in settings.json env (config.claudeSettingsPath)
const Settings = z.object({
  env: z
    .object({
      ANTHROPIC_BASE_URL: z.string(),
      ANTHROPIC_AUTH_TOKEN: z.string(),
      ANTHROPIC_DEFAULT_OPUS_MODEL: z.string(),
      ANTHROPIC_DEFAULT_SONNET_MODEL: z.string(),
      ANTHROPIC_DEFAULT_HAIKU_MODEL: z.string(),
    })
    .loose(),
});

export function claudeSettingsEnv(
  file: string = config.claudeSettingsPath,
): z.infer<typeof Settings>['env'] {
  const raw: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
  return Settings.parse(raw).env;
}

const env = claudeSettingsEnv();

// [1m] in an alias is Claude Code's context tag, which the Messages API rejects
export const stripContextTag = (model: string) => model.replace(/\[[^\]]*\]$/, '');

export interface Models {
  simulatedUser: string;
  judge: string;
}

// Defaults: simulated user and judge both use claude-sonnet-5-5 (user's choice, Contracts 4): since 2026-10-12 opus on the gateway ignores the prompt's
// count and format rules, and acceptance-criteria grading was refused upstream every time (Reports/W33). Settings in the database override these
export const DEFAULT_ROLE_MODEL = 'claude-sonnet-5-5';

export function defaultModels(): Models {
  return { simulatedUser: DEFAULT_ROLE_MODEL, judge: DEFAULT_ROLE_MODEL };
}

// Models in effect; callers read them at call time, PUT /api/settings rewrites them at once via setModels
export const models: Models = defaultModels();

export function setModels(next: Models) {
  Object.assign(models, next);
}

let client: Anthropic | undefined;

export function gatewayClient(baseURL: string, authToken: string): Anthropic {
  return new Anthropic({
    baseURL,
    authToken,
    apiKey: null,
    // No automatic retry: gateway 429 / 5xx / connection errors go straight to the caller
    maxRetries: 0,
    // A hung request fails with a timeout after 10 minutes (Contracts 4): settling a long ticket's acceptance criteria measured 84-132 seconds
    timeout: 600_000,
  });
}

export function anthropic(): Anthropic {
  client ??= gatewayClient(env.ANTHROPIC_BASE_URL, env.ANTHROPIC_AUTH_TOKEN);
  return client;
}

export interface StructuredResult<T> {
  value: T;
  usage: TokenUsage;
  costUsd: number;
  model: string;
}

// Structured output (Contracts 4): one strict tool respond, tool_choice auto, with the end of the system prompt requiring the call;
// the structure is read from tool_use.input. Constrained decoding via output_config on the gateway often returns empty strings or placeholder words
const OUTPUT_TOOL = 'respond';
const OUTPUT_RULE = `\n\n## Submitting the result\nYou must submit the final result by calling the ${OUTPUT_TOOL} tool, with all of the result in its arguments; do not answer with text only.`;
const ToolInputSchema = z.looseObject({ type: z.literal('object') });

export interface StructuredRequest<T> {
  model: string;
  system: string;
  user: string;
  schema: z.ZodType<T>;
  maxTokens: number;
}

// The structured output request, shared by parseStructured and the environment check, which sends the same kind of request as real judging, grading and the simulated user
// (when the gateway routes the model to a channel that rejects strict tools, the environment check fails too)
export function structuredRequest<T>(args: StructuredRequest<T>): MessageCreateParamsNonStreaming {
  return {
    model: args.model,
    max_tokens: args.maxTokens,
    system: `${args.system}${OUTPUT_RULE}`,
    messages: [{ role: 'user', content: args.user }],
    tools: [
      {
        name: OUTPUT_TOOL,
        description: 'Submit the final result.',
        // zodOutputFormat is generated by z.toJSONSchema and reduced to the strict subset (integer ranges, string lengths etc. move into description);
        // those constraints are checked by schema.parse in parseStructuredResponse
        input_schema: ToolInputSchema.parse(zodOutputFormat(args.schema).schema),
        strict: true,
      },
    ],
    tool_choice: { type: 'auto' },
  };
}

// Read the structure from the response's respond call; throws when refused upstream, not called or not matching the schema
export function parseStructuredResponse<T>(
  response: Message,
  schema: z.ZodType<T>,
  model: string,
): StructuredResult<T> {
  // The refusal classifier may stop the respond call after it starts, leaving tool_use input empty (Reports/W31b): check stop_reason first
  if (response.stop_reason === 'refusal') {
    const details = response.stop_details;
    throw new Error(
      `Structured output refused upstream (stop_reason=refusal): category=${String(details?.category ?? null)}, explanation=${String(details?.explanation ?? null)}`,
    );
  }
  const call = response.content.find((block) => block.type === 'tool_use');
  if (call?.type !== 'tool_use') {
    throw new Error(
      `Structured output did not call ${OUTPUT_TOOL} (stop_reason=${String(response.stop_reason)}): ${JSON.stringify(response.content)}`,
    );
  }
  const usage = fromApiUsage(response.usage);
  return { value: schema.parse(call.input), usage, costUsd: costUsd(usage, model), model };
}

// The environment check each role's real calls report into (Contracts 8)
export const roleCheckIds: Record<keyof Models, PaidCheckId> = {
  simulatedUser: 'model-simulated-user',
  judge: 'model-judge',
};

export function parseStructured<T>(
  args: StructuredRequest<T> & {
    // The role the call is made for; its outcome is that role's environment check. null for a probe outside any role
    role: keyof Models | null;
    // Abort the in-flight request when grading is cancelled
    signal?: AbortSignal;
  },
): Promise<StructuredResult<T>> {
  const started = performance.now();
  const outcome = anthropic()
    .messages.create(
      structuredRequest(args),
      args.signal === undefined ? {} : { signal: args.signal },
    )
    .then((response) => parseStructuredResponse(response, args.schema, args.model));
  const role = args.role;
  if (role === null) return outcome;
  // Only a call with the role's current model is real use of its check; a cancelled call says nothing about it. An
  // answer whose content does not match the schema still proves the model answered with respond
  const report = (usage: PaidUsage) => {
    if (args.model === models[role]) reportPaidUsage(roleCheckIds[role], usage);
  };
  const answered = () =>
    `${args.model} answered with respond in ${String(Math.round(performance.now() - started))} ms`;
  void outcome.then(
    () => {
      report({ ok: true, detail: answered() });
    },
    (error: unknown) => {
      if (args.signal?.aborted === true) return;
      if (error instanceof z.ZodError) {
        report({ ok: true, detail: `${answered()}; its content did not match the schema` });
        return;
      }
      report({ ok: false, detail: error instanceof Error ? error.message : String(error) });
    },
  );
  return outcome;
}
